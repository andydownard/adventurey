import { chromium } from 'playwright';
const out = 'test-results/'; (await import('node:fs')).mkdirSync(out, { recursive: true });
const browser = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 800 } });
const errors = [];
page.on('console', (m) => { if (m.type() === 'error' || m.type() === 'warning') errors.push(m.type() + ': ' + m.text()); });
page.on('pageerror', (e) => errors.push('pageerror: ' + e.message));
await page.goto('http://localhost:4173/');
await page.waitForTimeout(1500);
await page.screenshot({ path: out + '1-title.png' });
await page.click('.moon'); await page.keyboard.type('Wolf'); await page.keyboard.press('Enter');
await page.getByRole('button', { name: 'Play', exact: true }).click();
await page.waitForTimeout(800);
await page.screenshot({ path: out + '2-gear.png' });
await page.getByRole('button', { name: /Next/ }).click();
await page.waitForTimeout(800);
await page.screenshot({ path: out + '3-pack.png' });
await page.getByRole('button', { name: 'Go to camp' }).click();
await page.waitForTimeout(2500);
await page.screenshot({ path: out + '4-intro.png' });
await page.getByRole('button', { name: 'Start the night' }).click();
await page.waitForTimeout(500);
await page.keyboard.down('d'); await page.waitForTimeout(600); await page.keyboard.up('d');
await page.waitForTimeout(6000);
for (let i = 0; i < 6; i++) { await page.mouse.click(300 + i * 120, 250); await page.keyboard.press('Space'); await page.waitForTimeout(250); }
await page.screenshot({ path: out + '5-play.png' });
await page.waitForTimeout(9000);
await page.keyboard.down('Space'); await page.waitForTimeout(400); await page.keyboard.up('Space');
await page.screenshot({ path: out + '6-play-later.png' });
const st = await page.evaluate(() => { const s = window.__adventurey.scene().s; return { t: s.t, camp: s.campHealth, monsters: s.monsters.length, bonks: s.bonks, hero: s.hero.pos }; });
console.log('STATE', JSON.stringify(st));
await page.evaluate(() => { const s = window.__adventurey.scene().s; s.t = s.length - 0.2; });
await page.waitForTimeout(4500);
await page.screenshot({ path: out + '7-result.png' });
console.log('ERRORS', errors.length, errors.slice(0, 15).join('\n'));
await browser.close();
